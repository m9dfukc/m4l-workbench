#!/usr/bin/env python3
"""Dial probe for standalone Max (face-review h.4, decision D42): which size does a jspainter get on
a live.dial with showname 1 / shownumber 1, and does the saved height matter?

Writes OUTDIR/dialprobe.maxpat (five live.dial boxes p_a ... p_e, opened in presentation) and
OUTDIR/dialprobe_painter.js (ES5 jspainter that posts one "dialprobe ..." line per box). The patch
quits Max after a few seconds. Run it with run_dialprobe.sh; never Live, never the user's patches.

Usage: python3 devices/aliasing/test/dial-probe/make_dialprobe.py OUTDIR
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "scripts"))
import bootstrap_shell as bs  # noqa: E402

# varname, showname, shownumber, saved rect h, fontsize, expectation (face-review h.4)
DIALS = [
    ("p_a", 1, 1, 48, 9.5, "47-48 -> hybrid as drawn"),
    ("p_b", 1, 1, 60, 9.5, "47-48 again = height fixed"),
    ("p_c", 0, 1, 45, 9.0, "36 = confirms face-review 1"),
    ("p_d", 1, 1, 48, 12.0, "taller with a larger font?"),
    ("p_e", 0, 0, 48, 9.5, "27-28"),
]

PAINTER = r"""// dialprobe_painter.js: generated by make_dialprobe.py (dial probe, face-review h.4). Plain ES5.
var reported = false;
function attr(n) {
	try {
		var v = box.getattr(n);
		if (v && typeof v === "object" && v.length !== undefined) return Array.prototype.join.call(v, " ");
		return v;
	} catch (e) {
		return "?";
	}
}
attr.local = 1;
function paint() {
	var s = mgraphics.size;
	if (!reported) {
		reported = true;
		var vn = "?";
		try { vn = box.varname; } catch (e) {}
		post("dialprobe", vn, "size", s[0], s[1], "rect", attr("patching_rect"), "pres", attr("presentation_rect"),
			"name", attr("showname"), "number", attr("shownumber"), "font", attr("fontsize"),
			"appearance", attr("appearance"), "\n");
	}
	mgraphics.set_source_rgba(0.5, 0.5, 0.5, 1);
	mgraphics.rectangle(0.5, 0.5, s[0] - 1, s[1] - 1);
	mgraphics.set_line_width(1);
	mgraphics.stroke();
}
"""


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__)
        return 2
    out = Path(argv[0]).resolve()
    out.mkdir(parents=True, exist_ok=True)
    (out / "dialprobe_painter.js").write_text(PAINTER)
    boxes: list[dict] = []
    lines: list[dict] = []
    for i, (var, sn, nb, h, fs, _) in enumerate(DIALS):
        rect = [20.0 + 70.0 * i, 20.0, 42.0, float(h)]
        boxes.append({"box": {
            "id": f"obj-{i + 1}", "maxclass": "live.dial", "numinlets": 1, "numoutlets": 2,
            "outlettype": ["", "float"], "parameter_enable": 1, "jspainterfile": "dialprobe_painter.js",
            "varname": var, "showname": sn, "shownumber": nb, "fontsize": fs,
            "patching_rect": rect, "presentation": 1, "presentation_rect": rect,
            "saved_attribute_attributes": {"valueof": bs.valueof(f"Probe {var}", var, bs.T_FLOAT,
                                                                 mmin=0.0, mmax=1.0, initial=0.5)}}})
    n = len(DIALS)

    def add(text: str, y: float, outs: list[str], maxclass: str = "newobj") -> str:
        nonlocal n
        n += 1
        boxes.append({"box": {"id": f"obj-{n}", "maxclass": maxclass, "text": text, "numinlets": 2 if maxclass == "message" else 1,
                              "numoutlets": len(outs), "outlettype": outs,
                              "patching_rect": [20.0, y, 200.0, 22.0]}})
        return f"obj-{n}"

    lb = add("loadbang", 140, ["bang"])
    dl = add("delay 4000", 170, ["bang"])
    q = add("; max clean; max quit", 200, [""], "message")
    lines += [{"patchline": {"source": [lb, 0], "destination": [dl, 0]}},
              {"patchline": {"source": [dl, 0], "destination": [q, 0]}}]
    pat = {"patcher": {"fileversion": 1, "appversion": {"major": 9, "minor": 2, "revision": 1,
                                                        "architecture": "x64", "modernui": 1},
                       "classnamespace": "box", "rect": [60.0, 80.0, 420.0, 260.0],
                       "openinpresentation": 1, "boxes": boxes, "lines": lines}}
    (out / "dialprobe.maxpat").write_text(json.dumps(pat, indent=1))
    print(f"wrote {out / 'dialprobe.maxpat'}")
    for var, sn, nb, h, fs, exp in DIALS:
        print(f"  {var}: showname {sn} shownumber {nb} saved h {h} fontsize {fs} -> expect {exp}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
